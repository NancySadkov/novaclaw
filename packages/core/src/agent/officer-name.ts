/** How many times a taken name is re-rolled before the numeric fallback. Small on purpose: with a
 *  pool this size a collision means the roster is already large, and re-rolling forever to avoid a
 *  suffix spends attempts hiding a fact the user can see anyway. */
export const REROLLS = 3

/**
 * Pick a name for a new officer.
 *
 * `taken` is compared case-insensitively against BOTH ids and display names, because a duplicate
 * causes a READING confusion, not a key collision — two colleagues shown as "Theron" are
 * indistinguishable in a hand-off line even when their ids differ.
 *
 * ⚠️ `random` is injected. A module reaching for `Math.random` is untestable by construction, and the
 * one property worth pinning — that a collision resolves rather than loops or throws — needs a
 * deterministic draw to be pinned at all.
 */
export const pick = (input: {
  readonly taken: Iterable<string>
  readonly random: () => number
  readonly pool?: readonly string[]
}): string => {
  const pool = input.pool ?? POOL
  const taken = new Set([...input.taken].map((value) => value.trim().toLowerCase()).filter(Boolean))
  const draw = () => pool[Math.min(pool.length - 1, Math.max(0, Math.floor(input.random() * pool.length)))]!
  let candidate = draw()
  for (let attempt = 0; attempt < REROLLS && taken.has(candidate); attempt++) candidate = draw()
  if (!taken.has(candidate)) return candidate
  // Every re-roll landed on a taken name. Number it rather than scanning the pool exhaustively: the
  // suffix is honest ("there are already Therons here") and always terminates, where a scan can still
  // fail on a roster that holds the whole pool.
  for (let index = 2; ; index++) {
    const numbered = `${candidate}-${index}`
    if (!taken.has(numbered)) return numbered
  }
}

/** The display form of a pool name. The store keeps the slug; people read the capitalised name. */
export const display = (name: string): string =>
  name
    .split("-")
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ")
